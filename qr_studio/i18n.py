from __future__ import annotations

import locale
import os
import subprocess
import sys

LANGUAGES = {"en": "English", "ar": "العربية"}
SYSTEM = "system"  # setting value: follow the operating system language


def _system_language_codes() -> list[str]:
    """Preferred UI languages of the OS, most preferred first (e.g. ["en-IQ", "ar-IQ"])."""
    codes: list[str] = []
    if sys.platform == "darwin":
        # Apps started from Finder get no LANG variable, so ask macOS directly.
        try:
            out = subprocess.run(["defaults", "read", "-g", "AppleLanguages"], capture_output=True,
                                 text=True, timeout=3).stdout
            codes += [part.strip().strip('",') for part in out.splitlines()
                      if part.strip() not in ("(", ")", "")]
        except (OSError, subprocess.SubprocessError):
            pass
    elif sys.platform.startswith("win"):
        try:
            import ctypes

            lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()  # type: ignore[attr-defined]
            primary = lang_id & 0x3FF
            codes.append({0x01: "ar", 0x09: "en"}.get(primary, locale.windows_locale.get(lang_id, "")))
        except (OSError, AttributeError):
            pass
    for var in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"):
        if os.environ.get(var):
            codes += os.environ[var].split(":")
    try:
        codes.append(locale.getlocale()[0] or "")
    except ValueError:
        pass
    return [c for c in codes if c]


def system_language() -> str:
    """The first OS language the app supports, else English."""
    for code in _system_language_codes():
        short = code.replace("_", "-").split("-")[0].lower()
        if short in LANGUAGES:
            return short
    return "en"


def resolve_language(setting: str) -> str:
    return setting if setting in LANGUAGES else system_language()

